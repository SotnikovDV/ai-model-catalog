function slugify(label) {
  return label
    .toLowerCase()
    .replace(/[^a-zа-яё0-9]+/gi, '_')
    .replace(/^_|_$/g, '')
    .slice(0, 60);
}

const useCases = [];
const labelToCanonical = new Map();
const categoryDefaultUseCase = new Map();

for (const cat of categories) {
  const labels = useCasesByCategory[cat.id] ?? [];
  categoryDefaultUseCase.set(cat.id, labels[0] ?? null);
  for (const label of labels) {
    const id = `${cat.id}__${slugify(label)}`;
    useCases.push({ id, label, categoryId: cat.id });
    labelToCanonical.set(label, label);
  }
}

