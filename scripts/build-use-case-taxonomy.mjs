const aliases = {};

// legacy → canonical через старую категорию
for (const [oldCat, legacyList] of Object.entries(canonicalMap)) {
  const newCatId = oldCategoryToNew[oldCat];
  if (!newCatId) continue;
  const defaultLabel = categoryDefaultUseCase.get(newCatId);
  if (!defaultLabel) continue;
  for (const legacy of legacyList) {
    if (!labelToCanonical.has(legacy)) {
      aliases[legacy] = defaultLabel;
    }
  }
}

